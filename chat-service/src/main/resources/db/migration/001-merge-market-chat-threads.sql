-- Yangi bazada Liquibase Hibernate'dan oldin ishlaydi. Mavjud bazada bu CREATE'lar o'tkazib yuboriladi.
CREATE TABLE IF NOT EXISTS chat_threads (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    buyer_id bigint,
    seller_company_id bigint,
    product_id bigint,
    application_id bigint,
    vacancy_id bigint,
    buyer_hidden boolean,
    seller_hidden boolean,
    last_message_at timestamp(6),
    created_date timestamp(6),
    modified_date timestamp(6),
    created_by bigint,
    modified_by bigint,
    deleted boolean NOT NULL DEFAULT false
);

CREATE TABLE IF NOT EXISTS chat_messages (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    thread_id bigint NOT NULL REFERENCES chat_threads(id),
    sender_id bigint,
    sender_type varchar(255),
    body text,
    attachment_key varchar(255),
    attachment_url varchar(255),
    sent_at timestamp(6),
    delivered_at timestamp(6),
    buyer_read_at timestamp(6),
    seller_read_at timestamp(6),
    created_date timestamp(6),
    modified_date timestamp(6),
    created_by bigint,
    modified_by bigint,
    deleted boolean NOT NULL DEFAULT false
);

-- Ko'chirish paytida boshqa sessiyalar yangi chat yoki xabar yozishini kutdiramiz.
LOCK TABLE chat_threads, chat_messages IN SHARE ROW EXCLUSIVE MODE;

-- Jobs chat yangilanishi avval qo'llanmagan bo'lsa, ustunlarni shu yerda yaratamiz.
ALTER TABLE chat_threads ADD COLUMN IF NOT EXISTS application_id bigint;
ALTER TABLE chat_threads ADD COLUMN IF NOT EXISTS vacancy_id bigint;
CREATE UNIQUE INDEX IF NOT EXISTS uk_chat_threads_application_id ON chat_threads(application_id);

-- Avvalgi global unique constraint nomini Hibernate har xil yaratishi mumkin.
-- Faqat eski juftlik/uchlikni olib tashlaymiz. Application ID cheklovi alohida qoladi.
DO $$
DECLARE
    legacy_constraint record;
BEGIN
    FOR legacy_constraint IN
        SELECT c.conname
        FROM pg_constraint c
        WHERE c.conrelid = 'chat_threads'::regclass AND c.contype = 'u'
          AND ARRAY(
              SELECT a.attname::text
              FROM unnest(c.conkey) AS k(attnum)
              JOIN pg_attribute a ON a.attrelid = c.conrelid AND a.attnum = k.attnum
              ORDER BY a.attname
          ) IN (ARRAY['buyer_id', 'seller_company_id'], ARRAY['buyer_id', 'product_id', 'seller_company_id'])
    LOOP
        EXECUTE format('ALTER TABLE chat_threads DROP CONSTRAINT %I', legacy_constraint.conname);
    END LOOP;
END $$;

-- Har bir faol savdo chatlari guruhida eng eski ID'ni saqlaymiz.
-- Arxivlangan va ishga ariza chati yozuvlari guruhga kirmaydi.
CREATE TEMP TABLE market_chat_merge_map ON COMMIT DROP AS
SELECT id AS old_id, keep_id
FROM (
    SELECT id, min(id) OVER (PARTITION BY buyer_id, seller_company_id) AS keep_id
    FROM chat_threads
    WHERE application_id IS NULL AND deleted = false
      AND buyer_id IS NOT NULL AND seller_company_id IS NOT NULL
) grouped
WHERE id <> keep_id;

-- Faqat bog'lanish o'zgaradi. Xabar ID'si, matni, fayli va o'qilgan holati saqlanadi.
UPDATE chat_messages AS m SET thread_id = map.keep_id
FROM market_chat_merge_map AS map
WHERE m.thread_id = map.old_id;

-- Kamida bitta suhbat tomonga ko'ringan bo'lsa, asosiy chat ham ko'rinadi.
WITH members AS (
    SELECT old_id AS thread_id, keep_id FROM market_chat_merge_map
    UNION
    SELECT keep_id, keep_id FROM market_chat_merge_map
), visibility AS (
    SELECT m.keep_id,
           bool_and(coalesce(t.buyer_hidden, false)) AS buyer_hidden,
           bool_and(coalesce(t.seller_hidden, false)) AS seller_hidden
    FROM members m JOIN chat_threads t ON t.id = m.thread_id
    GROUP BY m.keep_id
)
UPDATE chat_threads AS t SET buyer_hidden = v.buyer_hidden,
    seller_hidden = v.seller_hidden,
    last_message_at = (SELECT max(m.sent_at) FROM chat_messages m WHERE m.thread_id = t.id AND m.deleted = false)
FROM visibility v WHERE t.id = v.keep_id;

-- Eski chat qatorlarini o'chirish o'rniga arxivlaymiz.
UPDATE chat_threads AS t SET deleted = true, modified_date = current_timestamp
FROM market_chat_merge_map AS map WHERE t.id = map.old_id;

-- Faqat faol savdo chatlari yagona bo'ladi. Ishga ariza chatlari bu indeksga kirmaydi.
CREATE UNIQUE INDEX uk_chat_threads_active_market_pair
    ON chat_threads(buyer_id, seller_company_id)
    WHERE application_id IS NULL AND deleted = false;
