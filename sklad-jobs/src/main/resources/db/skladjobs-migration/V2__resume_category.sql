-- Flyway runs before Hibernate. Support both new and existing installations.
CREATE TABLE IF NOT EXISTS resume (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_date TIMESTAMP(6),
    modified_date TIMESTAMP(6),
    created_by BIGINT,
    modified_by BIGINT,
    deleted BOOLEAN NOT NULL DEFAULT FALSE,
    candidate_id BIGINT NOT NULL,
    file_id VARCHAR(255),
    title VARCHAR(255) NOT NULL,
    full_name VARCHAR(255) NOT NULL,
    phone VARCHAR(32) NOT NULL,
    email VARCHAR(255) NOT NULL,
    region_id BIGINT NOT NULL,
    desired_position VARCHAR(255),
    expected_salary NUMERIC(19,2),
    about_me TEXT,
    skills TEXT,
    work_experience TEXT,
    education TEXT,
    languages TEXT
);

-- Legacy resumes have no known category; keep them until their owner selects one.
-- New create/update requests still require categoryId through ResumeRequest validation.
ALTER TABLE resume ADD COLUMN IF NOT EXISTS category_id BIGINT;
ALTER TABLE resume ADD CONSTRAINT fk_resume_job_category
    FOREIGN KEY (category_id) REFERENCES job_category(id);
CREATE INDEX IF NOT EXISTS idx_resume_category_id ON resume(category_id);
