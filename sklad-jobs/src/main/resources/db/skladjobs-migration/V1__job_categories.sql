CREATE TABLE IF NOT EXISTS job_category (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_date TIMESTAMP(6),
    modified_date TIMESTAMP(6),
    created_by BIGINT,
    modified_by BIGINT,
    deleted BOOLEAN NOT NULL DEFAULT FALSE,
    name_uz VARCHAR(255) NOT NULL,
    name_ru VARCHAR(255) NOT NULL,
    name_en VARCHAR(255) NOT NULL,
);

-- Flyway runs before Hibernate, so this also supports a fresh database.
-- On existing installations, the vacancy table and its data are preserved.
CREATE TABLE IF NOT EXISTS vacancy (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_date TIMESTAMP(6),
    modified_date TIMESTAMP(6),
    created_by BIGINT,
    modified_by BIGINT,
    deleted BOOLEAN NOT NULL DEFAULT FALSE,
    position_name VARCHAR(255),
    company_id BIGINT,
    buyer_id BIGINT,
    price NUMERIC(38,2),
    employment_type VARCHAR(255),
    work_schedule VARCHAR(255),
    short_description VARCHAR(255),
    views_count_cache BIGINT,
    vacancy_status VARCHAR(255),
    comment VARCHAR(255),
    region_id BIGINT,
    address VARCHAR(255),
    lng VARCHAR(255),
    lat VARCHAR(255),
    experience_level VARCHAR(255),
    requirements TEXT,
    working_conditions TEXT,
    show_contacts BOOLEAN,
    published_at TIMESTAMP(6) WITH TIME ZONE
);

-- Existing vacancies remain uncategorized until an owner selects a category.
ALTER TABLE vacancy ADD COLUMN IF NOT EXISTS category_id BIGINT;
ALTER TABLE vacancy ADD CONSTRAINT fk_vacancy_job_category
    FOREIGN KEY (category_id) REFERENCES job_category(id);
CREATE INDEX idx_vacancy_category_id ON vacancy(category_id);
