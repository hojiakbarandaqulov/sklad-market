-- Jobs-owned additive tables. Existing resumes stay private; no backfill or data modification.
CREATE TABLE IF NOT EXISTS jobs_resume_discovery (
    resume_id BIGINT PRIMARY KEY,
    enabled BOOLEAN NOT NULL DEFAULT FALSE,
    specialty VARCHAR(120), experience_level VARCHAR(255), region_id BIGINT,
    skills VARCHAR(1600), consented_at TIMESTAMP WITH TIME ZONE, consent_version VARCHAR(20)
);
CREATE INDEX IF NOT EXISTS idx_jobs_discovery_active_region ON jobs_resume_discovery (enabled, region_id, resume_id);
CREATE TABLE IF NOT EXISTS jobs_ai_invitation (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    inviter_id BIGINT NOT NULL, candidate_id BIGINT NOT NULL,
    resume_id BIGINT NOT NULL, vacancy_id BIGINT NOT NULL,
    request_id VARCHAR(36) NOT NULL, message VARCHAR(1000), status VARCHAR(20) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL, expires_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_jobs_invitation_request UNIQUE (inviter_id, request_id)
);
CREATE UNIQUE INDEX IF NOT EXISTS uk_jobs_invitation_pending ON jobs_ai_invitation (vacancy_id,candidate_id) WHERE status='PENDING';
CREATE INDEX IF NOT EXISTS idx_jobs_invitation_incoming ON jobs_ai_invitation (candidate_id,id DESC);
CREATE INDEX IF NOT EXISTS idx_jobs_invitation_outgoing ON jobs_ai_invitation (inviter_id,id DESC);
CREATE INDEX IF NOT EXISTS idx_jobs_invitation_limit ON jobs_ai_invitation (inviter_id,vacancy_id,created_at);
CREATE INDEX IF NOT EXISTS idx_jobs_invitation_global_limit ON jobs_ai_invitation (inviter_id,created_at);

-- Existing installations have the base tables; on an empty database Hibernate creates
-- those after Flyway. Do not make first startup fail before the existing schema bootstrap.
DO $$ BEGIN
    IF to_regclass('resume') IS NOT NULL THEN
        IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname='fk_jobs_discovery_resume' AND conrelid='jobs_resume_discovery'::regclass) THEN
            ALTER TABLE jobs_resume_discovery ADD CONSTRAINT fk_jobs_discovery_resume FOREIGN KEY(resume_id) REFERENCES resume(id);
        END IF;
        IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname='fk_jobs_invitation_resume' AND conrelid='jobs_ai_invitation'::regclass) THEN
            ALTER TABLE jobs_ai_invitation ADD CONSTRAINT fk_jobs_invitation_resume FOREIGN KEY(resume_id) REFERENCES resume(id);
        END IF;
    END IF;
    IF to_regclass('vacancy') IS NOT NULL AND NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname='fk_jobs_invitation_vacancy' AND conrelid='jobs_ai_invitation'::regclass) THEN
        ALTER TABLE jobs_ai_invitation ADD CONSTRAINT fk_jobs_invitation_vacancy FOREIGN KEY(vacancy_id) REFERENCES vacancy(id);
    END IF;
END $$;
