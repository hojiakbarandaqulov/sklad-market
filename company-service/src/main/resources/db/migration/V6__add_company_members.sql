-- Kompaniya a'zoligini saqlaydi va mavjud kompaniya egalarini ADMIN sifatida qo'shadi.
CREATE TABLE company_members (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    company_id BIGINT NOT NULL REFERENCES company(id),
    profile_id BIGINT NOT NULL,
    role VARCHAR(16) NOT NULL,
    created_date TIMESTAMP,
    modified_date TIMESTAMP,
    created_by BIGINT,
    modified_by BIGINT,
    deleted BOOLEAN NOT NULL DEFAULT FALSE,
    CONSTRAINT uk_company_members_company_profile UNIQUE (company_id, profile_id),
    CONSTRAINT ck_company_members_role CHECK (role IN ('ADMIN', 'MEMBER'))
);

-- Foydalanuvchining faol kompaniyalarini profil ID orqali topish uchun.
CREATE INDEX idx_company_members_profile_deleted ON company_members (profile_id, deleted);

-- Kompaniya yaratilgan vaqtni va asoschi profilini a'zolik tarixida saqlaymiz.
INSERT INTO company_members (company_id, profile_id, role, created_date, created_by)
SELECT id, owner_user_id, 'ADMIN', COALESCE(created_date, LOCALTIMESTAMP), owner_user_id
FROM company
WHERE deleted_at IS NULL AND deleted IS FALSE AND owner_user_id IS NOT NULL;
