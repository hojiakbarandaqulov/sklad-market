CREATE TABLE company_member_audit (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    company_id BIGINT NOT NULL REFERENCES company(id),
    actor_profile_id BIGINT NOT NULL,
    target_profile_id BIGINT,
    action VARCHAR(24) NOT NULL CHECK (action IN ('MEMBERS_LISTED', 'MEMBER_ADDED', 'MEMBER_REMOVED')),
    occurred_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX idx_company_member_audit_company_time ON company_member_audit (company_id, occurred_at);
