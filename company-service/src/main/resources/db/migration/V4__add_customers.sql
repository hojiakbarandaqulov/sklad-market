CREATE TABLE IF NOT EXISTS customer (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    company_id BIGINT NOT NULL REFERENCES company(id),
    name VARCHAR(255) NOT NULL,
    contract_number VARCHAR(100) NOT NULL,
    phone VARCHAR(30),
    payment_term_days INTEGER NOT NULL CHECK (payment_term_days BETWEEN 1 AND 3650),
    contract_attach_id VARCHAR(255),
    contract_file_name VARCHAR(255),
    contract_content_type VARCHAR(255),
    contract_size_bytes BIGINT,
    version BIGINT,
    created_date TIMESTAMP,
    modified_date TIMESTAMP,
    created_by BIGINT,
    modified_by BIGINT,
    deleted BOOLEAN NOT NULL DEFAULT FALSE
);

CREATE INDEX IF NOT EXISTS idx_customer_company_deleted ON customer(company_id, deleted);
